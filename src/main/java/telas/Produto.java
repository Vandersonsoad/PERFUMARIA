    private void btnexcluirpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexcluirpActionPerformed
        // TODO add your handling code here:
        
        int linhaSelecionada = jTable1.getSelectedRow();
        
        if (linhaSelecionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecione um produto na tabela para excluir!");
            return;
        }
        
        int confirmacao = javax.swing.JOptionPane.showConfirmDialog(
            this, 
            "Tem certeza de que deseja excluir este produto?", 
            "Confirmar Exclusão", 
            javax.swing.JOptionPane.YES_NO_OPTION
        );
        
        if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
            try {
                int idProduto = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 0).toString());
                
                dao.ProdutoDAO pDao = new dao.ProdutoDAO();
                boolean sucesso = pDao.excluir(idProduto);
                
                if (sucesso) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Produto excluído com sucesso!");
                    preencherTabela();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Não foi possível excluir o produto.");
                }
                
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao tentar excluir: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnexcluirpActionPerformed

