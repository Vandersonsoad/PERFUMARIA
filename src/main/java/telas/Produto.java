    private void btnsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsalvarActionPerformed
        if (txtnome.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "O nome do produto é obrigatório!");
            txtnome.requestFocus();
            return;
        }
        
        if (txtcusto.getText().trim().isEmpty() || txtvenda.getText().trim().isEmpty() || txtestoque.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Todos os campos numéricos devem ser preenchidos!");
            return;
        }
        
        if (jComboBox1.getSelectedIndex() <= 0) { // Valida seleção no ComboBox
            javax.swing.JOptionPane.showMessageDialog(this, "Você precisa selecionar um fornecedor válido!");
            return;
        }
        
        try {
            model.Produto produto = new model.Produto();
            produto.setNome(txtnome.getText().trim());
            produto.setPrecoCusto(Double.parseDouble(txtcusto.getText().trim()));
            produto.setPrecoVenda(Double.parseDouble(txtvenda.getText().trim()));
            produto.setQuantidadeEstoque(Integer.parseInt(txtestoque.getText().trim()));
            
            // Pega o fornecedor selecionado na ComboBox
            dao.FornecedorDAO fDao = new dao.FornecedorDAO();
            String razaoSelecionada = jComboBox1.getSelectedItem().toString();
            model.Fornecedor fornecedorAssociado = fDao.buscarPorRazao(razaoSelecionada);
            
            if (fornecedorAssociado != null) {
                produto.setFornecedor(fornecedorAssociado); 
            } else {
                throw new Exception("Fornecedor selecionado não foi encontrado no banco de dados.");
            }
            
            // Salva no banco
            dao.ProdutoDAO pDao = new dao.ProdutoDAO();
            pDao.salvar(produto);
            
            javax.swing.JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso!");
            
            limparCampos();
            preencherTabela();
            
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha custo, venda e estoque usando apenas números!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar o produto: " + e.getMessage());
        }
    }
        
                                          

